export function getRegencies(province) {
  if (!province) return [];
  return REGIONS_BY_PROVINCE[province] || [
    `Kabupaten/Kota di ${province}`,
  ];
}

export function formatLocation(item = {}) {
  const parts = [item.address, item.city, item.province].filter(Boolean);
  return parts.length > 0 ? parts.join(", ") : "Indonesia";
}
